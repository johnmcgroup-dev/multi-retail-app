-- Wholesale/Retail Inventory with POS - offline-first database schema
-- This same schema will run both in the browser (offline, via sql.js/WASM)
-- and later on the real server (SQLite or Postgres), so data moves cleanly
-- from offline-first local storage to cloud sync without being redesigned.

-- TENANTS: each company/business using the app
CREATE TABLE IF NOT EXISTS tenants (
  id TEXT PRIMARY KEY,
  name TEXT NOT NULL,
  created_at TEXT NOT NULL DEFAULT (datetime('now'))
);

-- BRANCHES: outlets/warehouses belonging to a tenant (built now, used fully in a later module)
CREATE TABLE IF NOT EXISTS branches (
  id TEXT PRIMARY KEY,
  tenant_id TEXT NOT NULL REFERENCES tenants(id),
  name TEXT NOT NULL,
  is_active INTEGER NOT NULL DEFAULT 1,
  created_at TEXT NOT NULL DEFAULT (datetime('now'))
);

-- USERS: logins, scoped to a tenant, with a role
CREATE TABLE IF NOT EXISTS users (
  id TEXT PRIMARY KEY,
  tenant_id TEXT REFERENCES tenants(id), -- NULL only for super_admin
  branch_id TEXT REFERENCES branches(id),
  name TEXT NOT NULL,
  email TEXT NOT NULL UNIQUE,
  role TEXT NOT NULL CHECK (role IN ('super_admin','owner','admin','manager','cashier')),
  status TEXT NOT NULL DEFAULT 'active' CHECK (status IN ('active','invited','suspended')),
  created_at TEXT NOT NULL DEFAULT (datetime('now'))
);

-- INVITE CODES: generated by an Owner/Admin so a staff member can join
-- their specific tenant with a specific role already assigned, instead of
-- accidentally becoming the owner of a brand new tenant on sign-up.
CREATE TABLE IF NOT EXISTS invite_codes (
  id TEXT PRIMARY KEY,
  tenant_id TEXT NOT NULL REFERENCES tenants(id),
  code TEXT NOT NULL UNIQUE,
  role TEXT NOT NULL CHECK (role IN ('admin', 'manager', 'cashier')),
  branch_id TEXT REFERENCES branches(id),
  created_by TEXT NOT NULL REFERENCES users(id),
  used_by TEXT REFERENCES users(id),
  used_at TEXT,
  revoked INTEGER NOT NULL DEFAULT 0,
  created_at TEXT NOT NULL DEFAULT (datetime('now'))
);

-- CATEGORIES
CREATE TABLE IF NOT EXISTS categories (
  id TEXT PRIMARY KEY,
  tenant_id TEXT NOT NULL REFERENCES tenants(id),
  name TEXT NOT NULL
);

-- PRODUCTS: the core item record
CREATE TABLE IF NOT EXISTS products (
  id TEXT PRIMARY KEY,
  tenant_id TEXT NOT NULL REFERENCES tenants(id),
  branch_id TEXT REFERENCES branches(id),
  name TEXT NOT NULL,
  barcode TEXT,
  sku TEXT,
  category_id TEXT REFERENCES categories(id),
  quantity REAL NOT NULL DEFAULT 0,  -- base stock quantity (in "Piece" units)
  base_price REAL NOT NULL DEFAULT 0,
  created_at TEXT NOT NULL DEFAULT (datetime('now')),
  updated_at TEXT NOT NULL DEFAULT (datetime('now')),
  deleted_at TEXT  -- soft delete, needed later for sync conflict handling
);

-- PRODUCT VARIETIES: Piece, Roll, Bundle, Dozen, Packet, Carton, Half-X, etc.
CREATE TABLE IF NOT EXISTS product_varieties (
  id TEXT PRIMARY KEY,
  product_id TEXT NOT NULL REFERENCES products(id),
  name TEXT NOT NULL,         -- e.g. "Carton", "Half-Carton"
  qty REAL NOT NULL,          -- how many base units this variety represents
  price REAL NOT NULL,
  is_half_variant INTEGER NOT NULL DEFAULT 0,
  parent_variety_id TEXT REFERENCES product_varieties(id), -- for Half-X auto-calc link
  is_manual_override INTEGER NOT NULL DEFAULT 0
);

-- CART ITEMS: the live, in-progress sale. Rows here persist in the offline
-- database (not just memory), so the cart survives a page refresh, closing
-- the browser, or navigating away - it only empties on a completed sale or
-- the Clear button (see cart.js for that logic).
CREATE TABLE IF NOT EXISTS cart_items (
  id TEXT PRIMARY KEY,
  tenant_id TEXT NOT NULL REFERENCES tenants(id),
  product_id TEXT NOT NULL REFERENCES products(id),
  variety_id TEXT NOT NULL REFERENCES product_varieties(id),
  product_name TEXT NOT NULL,   -- snapshot, so cart still reads fine even if product is renamed later
  variety_name TEXT NOT NULL,
  unit_price REAL NOT NULL,
  base_units_per_item REAL NOT NULL, -- how many base (Piece) units one of this variety consumes
  branch_id TEXT REFERENCES branches(id),  -- carts are per user AND per branch
  user_id TEXT REFERENCES users(id),
  quantity REAL NOT NULL,
  created_at TEXT NOT NULL DEFAULT (datetime('now'))
);

-- CUSTOMERS: real customer records, so sales can be tracked per customer
-- and (if not fully paid) build an outstanding balance. Also carries a
-- running loyalty points balance, earned on purchases and redeemable later.
CREATE TABLE IF NOT EXISTS customers (
  id TEXT PRIMARY KEY,
  tenant_id TEXT NOT NULL REFERENCES tenants(id),
  name TEXT NOT NULL,
  phone TEXT,
  address TEXT,
  is_walkin INTEGER NOT NULL DEFAULT 0,
  balance REAL NOT NULL DEFAULT 0,        -- positive = customer owes the company
  loyalty_points INTEGER NOT NULL DEFAULT 0,
  created_at TEXT NOT NULL DEFAULT (datetime('now'))
);

-- CUSTOMER LEDGER: the running financial account history for a customer -
-- each sale made on credit, and each payment received against a balance.
CREATE TABLE IF NOT EXISTS customer_ledger (
  id TEXT PRIMARY KEY,
  tenant_id TEXT NOT NULL REFERENCES tenants(id),
  customer_id TEXT NOT NULL REFERENCES customers(id),
  sale_id TEXT REFERENCES sales(id),
  type TEXT NOT NULL CHECK (type IN ('sale_credit', 'payment', 'adjustment')),
  amount REAL NOT NULL,       -- always a positive number; 'type' gives its meaning
  balance_after REAL NOT NULL,
  payment_method TEXT,        -- only meaningful when type = 'payment'
  branch_id TEXT REFERENCES branches(id),
  note TEXT,
  created_at TEXT NOT NULL DEFAULT (datetime('now'))
);

-- LOYALTY LEDGER: a separate running history of points earned/redeemed,
-- mirroring customer_ledger's pattern but for points instead of money.
CREATE TABLE IF NOT EXISTS loyalty_ledger (
  id TEXT PRIMARY KEY,
  tenant_id TEXT NOT NULL REFERENCES tenants(id),
  customer_id TEXT NOT NULL REFERENCES customers(id),
  sale_id TEXT REFERENCES sales(id),
  type TEXT NOT NULL CHECK (type IN ('earn', 'redeem', 'adjustment')),
  points INTEGER NOT NULL,
  balance_after INTEGER NOT NULL,
  note TEXT,
  created_at TEXT NOT NULL DEFAULT (datetime('now'))
);

-- SALES: a completed, finalized transaction
CREATE TABLE IF NOT EXISTS sales (
  id TEXT PRIMARY KEY,
  tenant_id TEXT NOT NULL REFERENCES tenants(id),
  total REAL NOT NULL,                        -- this sale's own total (items only)
  amount_paid REAL NOT NULL DEFAULT 0,        -- how much of THIS sale's total was paid now
  previous_balance_paid REAL NOT NULL DEFAULT 0, -- extra paid now that went toward old debt
  payment_method TEXT NOT NULL DEFAULT 'cash',
  loyalty_points_earned INTEGER NOT NULL DEFAULT 0,
  branch_id TEXT REFERENCES branches(id),
  customer_id TEXT REFERENCES customers(id),
  customer_name TEXT,   -- snapshot at time of sale, so invoices stay stable
  customer_phone TEXT,  -- even if the customer record is edited later
  created_at TEXT NOT NULL DEFAULT (datetime('now'))
);

-- COMPANY SETTINGS: shown at the top of every invoice. One row per tenant.
-- Also holds the loyalty program's two rates.
CREATE TABLE IF NOT EXISTS company_settings (
  tenant_id TEXT PRIMARY KEY REFERENCES tenants(id),
  company_name TEXT NOT NULL DEFAULT '',
  address TEXT NOT NULL DEFAULT '',
  phone TEXT NOT NULL DEFAULT '',
  email TEXT NOT NULL DEFAULT '',
  points_per_amount REAL NOT NULL DEFAULT 0.1,   -- points earned per 1 unit of currency paid
  points_redeem_value REAL NOT NULL DEFAULT 1.0, -- currency value of 1 point when redeeming
  currency_code TEXT NOT NULL DEFAULT 'USD'
);

-- SALE ITEMS: a frozen snapshot of each cart line at the moment of sale
CREATE TABLE IF NOT EXISTS sale_items (
  id TEXT PRIMARY KEY,
  sale_id TEXT NOT NULL REFERENCES sales(id),
  product_id TEXT NOT NULL,
  variety_id TEXT NOT NULL,
  product_name TEXT NOT NULL,
  variety_name TEXT NOT NULL,
  unit_price REAL NOT NULL,
  quantity REAL NOT NULL,
  line_total REAL NOT NULL
);

-- EXPENSE CATEGORIES
CREATE TABLE IF NOT EXISTS expense_categories (
  id TEXT PRIMARY KEY,
  tenant_id TEXT NOT NULL REFERENCES tenants(id),
  name TEXT NOT NULL
);

-- EXPENSES: operating costs, tracked separately from stock purchases/sales,
-- so a Profit & Loss report can be built from Sales minus Expenses.
CREATE TABLE IF NOT EXISTS expenses (
  id TEXT PRIMARY KEY,
  tenant_id TEXT NOT NULL REFERENCES tenants(id),
  category_id TEXT REFERENCES expense_categories(id),
  amount REAL NOT NULL,
  description TEXT,
  payment_method TEXT NOT NULL DEFAULT 'cash',
  expense_date TEXT NOT NULL DEFAULT (date('now')),
  branch_id TEXT REFERENCES branches(id),
  created_at TEXT NOT NULL DEFAULT (datetime('now'))
);

-- STOCK ADJUSTMENTS: an audit trail every time stock is increased outside of
-- a normal sale (e.g. the quick "Add Stock" button in POS, or a restock).
CREATE TABLE IF NOT EXISTS stock_adjustments (
  id TEXT PRIMARY KEY,
  tenant_id TEXT NOT NULL REFERENCES tenants(id),
  product_id TEXT NOT NULL REFERENCES products(id),
  branch_id TEXT REFERENCES branches(id),
  quantity_added REAL NOT NULL,
  note TEXT,
  created_at TEXT NOT NULL DEFAULT (datetime('now'))
);

-- BRANCH STOCK: the real stock figure. The product catalog (name, barcode,
-- varieties, prices) is shared by the whole tenant, but how many units exist
-- is tracked separately per branch. products.quantity is a legacy column kept
-- only so older data can be migrated; nothing reads it anymore.
CREATE TABLE IF NOT EXISTS branch_stock (
  product_id TEXT NOT NULL REFERENCES products(id),
  branch_id TEXT NOT NULL REFERENCES branches(id),
  tenant_id TEXT NOT NULL REFERENCES tenants(id),
  quantity REAL NOT NULL DEFAULT 0,
  PRIMARY KEY (product_id, branch_id)
);

-- STOCK TRANSFERS: a permanent log of stock moved between two branches of
-- the same tenant.
CREATE TABLE IF NOT EXISTS stock_transfers (
  id TEXT PRIMARY KEY,
  tenant_id TEXT NOT NULL REFERENCES tenants(id),
  product_id TEXT NOT NULL REFERENCES products(id),
  from_branch_id TEXT NOT NULL REFERENCES branches(id),
  to_branch_id TEXT NOT NULL REFERENCES branches(id),
  quantity REAL NOT NULL,
  note TEXT,
  created_by TEXT REFERENCES users(id),
  created_at TEXT NOT NULL DEFAULT (datetime('now'))
);

-- SYNC METADATA: every table that needs offline<->cloud sync gets a row here
-- so we always know what changed locally and hasn't been pushed to the server yet.
CREATE TABLE IF NOT EXISTS sync_queue (
  id TEXT PRIMARY KEY,
  table_name TEXT NOT NULL,
  record_id TEXT NOT NULL,
  operation TEXT NOT NULL CHECK (operation IN ('insert','update','delete')),
  payload TEXT NOT NULL, -- JSON snapshot of the row
  created_at TEXT NOT NULL DEFAULT (datetime('now')),
  synced INTEGER NOT NULL DEFAULT 0
);
